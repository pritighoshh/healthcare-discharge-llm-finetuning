import re

def clean_text(x):
    if x is None:
        return ""
    x = re.sub(r"\s+", " ", x).strip()
    return x

def format_example(ex):
    src = clean_text(ex["brief_hospital_course"])
    tgt = clean_text(ex["discharge_instructions"])

    # Instruction prefix helps T5/FLAN models focus on the right behavior
