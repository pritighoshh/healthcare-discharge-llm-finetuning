MAX_SOURCE_LEN = 256
MAX_TARGET_LEN = 128


def tokenize_fn(batch):
    # Tokenize inputs + targets in one call (recommended way now)
    tok = tokenizer(
        batch["source_text"],
        max_length=MAX_SOURCE_LEN,
        truncation=True,
        text_target=batch["target_text"],
        max_length_target=MAX_TARGET_LEN,
        truncation_target=True
    )
    return tok

